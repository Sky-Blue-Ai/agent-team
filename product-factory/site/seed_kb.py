def main():
    with open(P, encoding='utf-8') as f:
        d = json.load(f)
    existing = set(x.get('title') for x in d.get('kb', []))
    fresh = [x for x in ITEMS if x['title'] not in existing]
    d['kb'] = fresh + d.get('kb', [])
    try:
        d['_rev'] = int(d.get('_rev', 0) or 0) + 1   # 外部写入也推进版本，让陈旧页面能被识别
    except Exception:
        d['_rev'] = 1
    d['updatedAt'] = time.strftime('%Y-%m-%dT%H:%M:%S.000Z', time.gmtime())
    with open(P, 'w', encoding='utf-8') as f:
        json.dump(d, f, ensure_ascii=False, indent=2)
    from collections import Counter
    print('新增 %d 条；知识库共 %d 条；_rev=%d' % (len(fresh), len(d['kb']), d['_rev']))
    print('分类分布:', dict(Counter(x['cat'] for x in d['kb'])))


if __name__ == '__main__':
    main()
